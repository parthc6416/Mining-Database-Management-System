-- Check USER_TABLES first. Oracle DDL commits implicitly.

CREATE TABLE MINE_SITE (
    MINE_ID NUMBER PRIMARY KEY,
    MINE_NAME VARCHAR2(100) NOT NULL,
    LOCATION VARCHAR2(100),
    MINERAL_TYPE VARCHAR2(80),
    DEPTH_METERS NUMBER(10,2),
    STATUS VARCHAR2(30)
);

CREATE TABLE MINERAL (
    MINERAL_ID NUMBER PRIMARY KEY,
    MINERAL_NAME VARCHAR2(100) NOT NULL,
    CATEGORY VARCHAR2(60),
    MARKET_PRICE NUMBER(12,2)
);

CREATE TABLE MINER (
    MINER_ID NUMBER PRIMARY KEY,
    MINE_ID NUMBER REFERENCES MINE_SITE(MINE_ID),
    MINER_NAME VARCHAR2(100) NOT NULL,
    JOB_ROLE VARCHAR2(80),
    PHONE VARCHAR2(30)
);

CREATE TABLE EQUIPMENT (
    EQUIPMENT_ID NUMBER PRIMARY KEY,
    MINE_ID NUMBER REFERENCES MINE_SITE(MINE_ID),
    EQUIPMENT_NAME VARCHAR2(100) NOT NULL,
    STATUS VARCHAR2(30),
    PURCHASE_COST NUMBER(14,2)
);

CREATE TABLE PRODUCTION_RECORD (
    RECORD_ID NUMBER PRIMARY KEY,
    MINE_ID NUMBER REFERENCES MINE_SITE(MINE_ID),
    MINERAL_ID NUMBER REFERENCES MINERAL(MINERAL_ID),
    PRODUCTION_DATE DATE,
    TONNES_PRODUCED NUMBER(14,2)
);

CREATE TABLE SAFETY_INSPECTION (
    INSPECTION_ID NUMBER PRIMARY KEY,
    MINE_ID NUMBER REFERENCES MINE_SITE(MINE_ID),
    INSPECTION_DATE DATE,
    INSPECTOR_NAME VARCHAR2(100),
    RESULT VARCHAR2(50),
    NOTES VARCHAR2(500)
);

